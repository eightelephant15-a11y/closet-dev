#!/usr/bin/env python3
"""Generates everything derived from taxonomy/garment_taxonomy.v*.json.

    python3 tool/gen_taxonomy.py          # (re)generate
    python3 tool/gen_taxonomy.py --check  # exit 1 if generated files are stale (CI)

Outputs (all committed; CI regenerates and diffs):
  api/app/domain/taxonomy_data.py                          the JSON as a Python constant
  app/lib/features/closet/domain/taxonomy_data.dart        the JSON as a Dart constant
  app/lib/features/closet/domain/taxonomy_labels.dart    id -> localised label (AppLocalizations)
  app/lib/l10n/app_en.arb                                  `tax*` keys (labels live in ARB, like every user-facing string)
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "taxonomy" / "garment_taxonomy.v1.json"
PY_OUT = ROOT / "api/app/domain/taxonomy_data.py"
DART_OUT = ROOT / "app/lib/features/closet/domain/taxonomy_data.dart"
LABELS_OUT = ROOT / "app/lib/features/closet/domain/taxonomy_labels.dart"
ARB = ROOT / "app/lib/l10n/app_en.arb"
HEADER = "GENERATED by tool/gen_taxonomy.py from taxonomy/garment_taxonomy.v1.json. Do not edit."


def camel(snake: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in snake.split("_"))


def arb_entries(t: dict) -> dict[str, str]:
    out: dict[str, str] = {}
    for c in t["categories"]:
        out[f"taxCat{camel(c['id'])}"] = c["label"]
        for s in c["subcategories"]:
            out[f"taxSub{camel(s['id'])}"] = s["label"]
    for key, prefix in [("palette", "taxColor"), ("patterns", "taxPattern"), ("seasons", "taxSeason"),
                        ("fits", "taxFit"), ("materials", "taxMaterial")]:
        for item in t[key]:
            out[f"{prefix}{camel(item['id'])}"] = item["label"]
    for f in t["formality"]:
        out[f"taxFormality{f['value']}"] = f["label"]
    return out


def render_labels(t: dict) -> str:
    def switch(name: str, prefix: str, ids: list[str]) -> str:
        cases = "\n".join(f"    '{i}' => {prefix}{camel(i)}," for i in ids)
        return f"  String {name}(String id) => switch (id) {{\n{cases}\n    _ => id,\n  }};\n"

    subs = [s["id"] for c in t["categories"] for s in c["subcategories"]]
    parts = [
        switch("taxCategory", "taxCat", [c["id"] for c in t["categories"]]),
        switch("taxSubcategory", "taxSub", subs),
        switch("taxColor", "taxColor", [p["id"] for p in t["palette"]]),
        switch("taxPattern", "taxPattern", [p["id"] for p in t["patterns"]]),
        switch("taxSeason", "taxSeason", [p["id"] for p in t["seasons"]]),
        switch("taxFit", "taxFit", [p["id"] for p in t["fits"]]),
        switch("taxMaterial", "taxMaterial", [p["id"] for p in t["materials"]]),
    ]
    formality = "\n".join(f"    {f['value']} => taxFormality{f['value']}," for f in t["formality"])
    parts.append(f"  String taxFormalityLabel(int value) => switch (value) {{\n{formality}\n    _ => '$value',\n  }};\n")
    return (
        f"// {HEADER}\n// ignore_for_file: type=lint\n\n"
        "import 'package:stylist/l10n/gen/app_localizations.dart';\n\n"
        "/// Localised names for taxonomy ids (labels live in the ARB, generated from the taxonomy).\n"
        "extension TaxonomyLabels on AppLocalizations {\n" + "\n".join(parts) + "}\n"
    )


def build() -> dict[Path, str]:
    t = json.loads(SRC.read_text())
    raw = json.dumps(t, indent=2)
    assert "'''" not in raw
    outputs = {
        PY_OUT: f'"""{HEADER}"""\n\nimport json\nfrom typing import Any\n\nTAXONOMY_JSON = r\'\'\'{raw}\'\'\'\nTAXONOMY: dict[str, Any] = json.loads(TAXONOMY_JSON)\n',
        DART_OUT: f"// {HEADER}\n\n/// The taxonomy document (see taxonomy/garment_taxonomy.v1.json).\nconst String taxonomyJson = '''\n{raw}''';\n",
        LABELS_OUT: render_labels(t),
    }
    arb = json.loads(ARB.read_text())
    arb = {k: v for k, v in arb.items() if not k.startswith(("taxCat", "taxSub", "taxColor", "taxPattern", "taxSeason", "taxFit", "taxMaterial", "taxFormality", "@taxCat", "@taxSub", "@taxColor", "@taxPattern", "@taxSeason", "@taxFit", "@taxMaterial", "@taxFormality"))}
    arb.update(arb_entries(t))
    outputs[ARB] = json.dumps(arb, indent=2) + "\n"
    return outputs


def main() -> int:
    outputs = build()
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs.items():
        if path.suffix == ".dart":
            # format-stable: write, format, compare
            pass
        if check:
            current = path.read_text() if path.exists() else ""
            if path.suffix == ".dart":
                current_cmp = current
                tmp = path.with_suffix(path.suffix + ".chk")
                tmp.write_text(text)
                subprocess.run(["dart", "format", str(tmp)], check=False, capture_output=True)
                text_cmp = tmp.read_text()
                tmp.unlink()
                if current_cmp != text_cmp:
                    stale.append(path)
            elif current != text:
                stale.append(path)
        else:
            path.write_text(text)
            if path.suffix == ".dart":
                subprocess.run(["dart", "format", str(path)], check=False, capture_output=True)
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("stale generated files:", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        print("run: python3 tool/gen_taxonomy.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
